// Bundles src/tools/checkCard.ts into one dependency-free file that sits next to
// the engine card guide, for agents that only have a link to the repository.
//
//   node scripts/build-card-check.js            write docs/engine-card-skill/check-card.cjs
//   node scripts/build-card-check.js --check    fail when the committed file is out of date

const fs = require('fs')
const path = require('path')
const esbuild = require('esbuild')

const root = path.join(__dirname, '..')
const outFile = path.join(root, 'docs', 'engine-card-skill', 'check-card.cjs')

const result = esbuild.buildSync({
  entryPoints: [path.join(root, 'src', 'tools', 'checkCard.ts')],
  bundle: true, platform: 'node', target: 'node18', format: 'cjs', write: false, logLevel: 'error',
  legalComments: 'none', banner: { js: '#!/usr/bin/env node\n// Generated by scripts/build-card-check.js from src/tools/checkCard.ts. Do not edit.' }
})
const text = result.outputFiles[0].text

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf-8') : ''
  if (current !== text) { console.error('docs/engine-card-skill/check-card.cjs is out of date. Run: node scripts/build-card-check.js'); process.exit(1) }
  console.log('check-card.cjs is up to date')
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, text, { mode: 0o755 })
  console.log(`Wrote ${path.relative(root, outFile)} (${Math.round(text.length / 1024)} KB)`)
}
